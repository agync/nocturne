#!/usr/bin/env bash
# Regenerate the TypeScript contract from crates/contract and write a barrel index.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
out=ui/src/engine/bindings
rm -rf "$out"
cargo test -q -p nocturne-contract > /dev/null
{
    printf '// Generated by scripts/bindings.sh. Do not edit.\n'
    for f in "$out"/*.ts; do
        name=$(basename "$f" .ts)
        printf 'export type { %s } from "./%s";\n' "$name" "$name"
    done
} > "$out/index.ts.tmp"
mv "$out/index.ts.tmp" "$out/index.ts"
