// Generates src/design/tokens.css from src/design/tokens.json. Run with `npm run tokens`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const FONT_STACK = {
  serif: (f) => `"${f.family}", ${f.fallback}`,
  sans: (f) => `"${f.family}", ${f.fallback}`,
  mono: (f) => `"${f.family}", ${f.fallback}`,
};

function palette(colours, indent) {
  return Object.entries(colours)
    .map(([k, v]) => `${indent}--${kebab(k)}: ${v};`)
    .join("\n");
}

function typeClasses(tokens) {
  return Object.entries(tokens.type)
    .map(([name, t]) => {
      const lines = [
        `  font-family: var(--font-${t.font});`,
        `  font-size: ${t.size};`,
        `  line-height: ${t.lineHeight};`,
        `  font-weight: ${t.weight};`,
      ];
      if (t.style) lines.push(`  font-style: ${t.style};`);
      if (t.tracking) lines.push(`  letter-spacing: ${t.tracking};`);
      if (t.transform) lines.push(`  text-transform: ${t.transform};`);
      if (t.font === "serif") lines.push("  font-optical-sizing: auto;");
      if (t.font === "mono") lines.push("  font-variant-numeric: tabular-nums;");
      return `.t-${kebab(name)} {\n${lines.join("\n")}\n}`;
    })
    .join("\n\n");
}

export function generate(tokens) {
  const light = tokens.color.light;
  const dark = tokens.color.dark;
  const print = tokens.color.print;
  const out = [];
  out.push("/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit. */");
  out.push(
    `:root,\n:root[data-theme="light"] {\n  color-scheme: light;\n${palette(light, "  ")}\n}`,
  );
  out.push(
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n    color-scheme: dark;\n${palette(dark, "    ")}\n  }\n}`,
  );
  out.push(`:root[data-theme="dark"] {\n  color-scheme: dark;\n${palette(dark, "  ")}\n}`);

  const fonts = Object.entries(tokens.font)
    .map(([k, f]) => `  --font-${k}: ${FONT_STACK[k](f)};`)
    .join("\n");
  const space = Object.entries(tokens.space)
    .map(([k, v]) => `  --s-${k}: ${v}px;`)
    .join("\n");
  const radius = Object.entries(tokens.radius)
    .map(([k, v]) => `  --r-${k}: ${v}px;`)
    .join("\n");
  const elevation = Object.entries(tokens.elevation)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
  const motion = Object.entries(tokens.motion)
    .map(([k, m]) => {
      const name = kebab(k);
      const lines = [`  --m-${name}-duration: ${m.duration}ms;`];
      if (m.easing) lines.push(`  --m-${name}-easing: ${m.easing};`);
      return lines.join("\n");
    })
    .join("\n");
  const sizes = Object.entries(tokens.size)
    .filter(([, v]) => typeof v === "number")
    .map(([k, v]) => `  --size-${kebab(k)}: ${v}px;`)
    .join("\n");
  const breakpoints = Object.entries(tokens.breakpoints)
    .map(([k, v]) => `  --bp-${k}: ${v}px;`)
    .join("\n");
  out.push(
    `:root {\n${fonts}\n${space}\n${radius}\n${elevation}\n${motion}\n${sizes}\n${breakpoints}\n}`,
  );
  out.push(
    `@media print {\n  :root,\n  :root[data-theme] {\n    color-scheme: light;\n    --ink: ${print.ink};\n    --ink2: ${print.ink};\n    --ink3: ${print.ink};\n    --sheet: ${print.paper};\n    --bg: ${print.paper};\n    --raised: ${print.paper};\n    --rule: ${print.rule};\n    --rule2: ${print.rule};\n  }\n}`,
  );
  out.push(typeClasses(tokens));
  return `${out.join("\n\n")}\n`;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "design");

export function readTokens() {
  return JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "tokens.css"), generate(readTokens()));
}
