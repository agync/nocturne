import type { EntityKind, EntityView, MemoryView, Receipt } from "../../bindings";
import { SAFETY_PREDICATES, type SeedContext } from "./common";

/** What Nocturne remembers, and who and what it is about. The memories screens own this file. */
export function memoriesSeed(ctx: SeedContext): { memories: MemoryView[]; entities: EntityView[] } {
  const { at, receipt, tuesdayText, thursdayText, friday } = ctx;

  const memory = (
    id: string,
    sentence: string,
    subject: string,
    predicate: string,
    object: string,
    receipts: Receipt[],
    extra: Partial<MemoryView> = {},
  ): MemoryView => ({
    id,
    sentence,
    subject,
    entityId: null,
    predicate,
    object,
    certainty: "fairlySure",
    status: "active",
    validFrom: null,
    validTo: null,
    due: null,
    learnedAt: receipts[0]?.keptAt ?? at(0, 0),
    lastUsed: null,
    letGoAt: null,
    keepForever: SAFETY_PREDICATES.has(predicate),
    private: false,
    suggestPrivate: false,
    was: null,
    receipts,
    ...extra,
  });

  const memories: MemoryView[] = [
    memory(
      "mem-swim",
      "Leo’s swimming is on Mondays at 17:30.",
      "Leo",
      "swimsOn",
      "Monday 17:30",
      [receipt("item-swim")],
      { entityId: "ent-leo", was: "Wednesday", certainty: "sure", lastUsed: at(-1, 17, 5) },
    ),
    memory(
      "mem-lake",
      "You decided to book the Lake District cottage for half term.",
      "You",
      "decided",
      "Lake District cottage",
      [receipt("item-lake", { type: "time", startMs: 0, endMs: 42000 })],
      { entityId: "ent-lake" },
    ),
    memory(
      "mem-gran",
      "Gran’s new number ends 4471.",
      "Gran",
      "phoneEndsWith",
      "4471",
      [receipt("item-gran")],
      { entityId: "ent-gran", certainty: "sure" },
    ),
    memory(
      "mem-trip",
      "The Year 4 trip form is due next Friday. It needs a signature and £12.",
      "Year 4 trip form",
      "dueOn",
      friday,
      [receipt("item-letter")],
      { due: friday, entityId: "ent-leo" },
    ),
    memory(
      "mem-dentist-tue",
      `Your dentist appointment is ${tuesdayText}.`,
      "Dentist appointment",
      "appointmentAt",
      tuesdayText,
      [receipt("item-card")],
      { status: "unconfirmed", certainty: "notSure", entityId: "ent-dentist" },
    ),
    memory(
      "mem-dentist-thu",
      `Your dentist appointment is ${thursdayText}.`,
      "Dentist appointment",
      "appointmentAt",
      thursdayText,
      [receipt("item-dentist-voice", { type: "time", startMs: 0, endMs: 8000 })],
      { status: "unconfirmed", certainty: "notSure", entityId: "ent-dentist" },
    ),
    memory(
      "mem-dentist-chen",
      "Leo’s dentist is Dr Chen at Willow Dental.",
      "Dr Chen",
      "dentistFor",
      "Leo",
      [receipt("item-dentist-chen")],
      { entityId: "ent-chen", certainty: "sure" },
    ),
    memory(
      "mem-coach",
      "Leo swims with Coach Sam.",
      "Leo",
      "swimsWith",
      "Coach Sam",
      [receipt("item-coach")],
      { entityId: "ent-leo", lastUsed: at(-9, 10, 15) },
    ),
    memory(
      "mem-leo-son",
      "Leo is your son.",
      "Leo",
      "relationship",
      "your son",
      [receipt("item-leo-son", { type: "quote", text: "My son Leo turns 9 in March." })],
      { entityId: "ent-leo", certainty: "sure" },
    ),
    memory(
      "mem-gym",
      "The old gym door code is 4821.",
      "Gym door code",
      "isCode",
      "4821",
      [receipt("item-gym")],
      { status: "letGo", letGoAt: at(0, 2, 10), lastUsed: at(-90, 8, 0) },
    ),
    memory(
      "mem-pizza",
      "The pizza place on Elm Street is good.",
      "Pizza place",
      "isGood",
      "Elm Street",
      [receipt("item-pizza")],
      { status: "letGo", letGoAt: at(0, 2, 10), lastUsed: at(-120, 19, 0) },
    ),
    memory(
      "mem-nut",
      "Leo is allergic to nuts.",
      "Leo",
      "allergicTo",
      "nuts",
      [receipt("item-nut", { type: "quote", text: "Leo is allergic to nuts so I always..." })],
      { status: "unconfirmed", certainty: "notSure", entityId: "ent-leo", suggestPrivate: true },
    ),
    memory(
      "mem-ava-penicillin",
      "Ava is allergic to penicillin.",
      "Ava",
      "allergicTo",
      "penicillin",
      [receipt("item-gp")],
      { entityId: "ent-ava", certainty: "sure", suggestPrivate: true },
    ),
    memory(
      "mem-gran-tablets",
      "Gran takes amlodipine 2.5 mg once a day.",
      "Gran",
      "takes",
      "amlodipine 2.5 mg",
      [receipt("item-prescription")],
      { entityId: "ent-gran", certainty: "sure", private: true, suggestPrivate: true },
    ),
    memory(
      "mem-gran-court",
      "Gran lives at Rowan Court.",
      "Gran",
      "livesAt",
      "Rowan Court",
      [receipt("item-gran-court")],
      { entityId: "ent-rowan", lastUsed: at(-40, 11, 0) },
    ),
    memory(
      "mem-jo",
      "Ava’s old swimming teacher is called Jo.",
      "Ava",
      "teacherIs",
      "Jo",
      [receipt("item-jo")],
      { status: "fading", entityId: "ent-ava", lastUsed: at(-67, 16, 0), certainty: "notSure" },
    ),
    memory(
      "mem-bin",
      "Bin day moved to Tuesdays over summer.",
      "Bin day",
      "movedTo",
      "Tuesdays",
      [receipt("item-bin")],
      { status: "fading", lastUsed: at(-84, 8, 0), certainty: "notSure", entityId: "ent-bin" },
    ),
    // What the school letter says, so "memories from it" has more than one line.
    memory(
      "mem-trip-where",
      "The Year 4 trip is to the Ridgeway Science Centre.",
      "Year 4 trip",
      "isTo",
      "Ridgeway Science Centre",
      [receipt("item-letter", { type: "quote", text: "Ridgeway Science Centre" })],
      { entityId: "ent-ridgeway", certainty: "sure" },
    ),
    memory(
      "mem-trip-lunch",
      "Leo needs a packed lunch on the trip day.",
      "Leo",
      "needs",
      "packed lunch",
      [receipt("item-letter", { type: "quote", text: "Packed lunches are needed" })],
      { entityId: "ent-leo" },
    ),
    memory(
      "mem-okafor",
      "Leo’s teacher is Mrs Okafor.",
      "Mrs Okafor",
      "teacherOf",
      "Leo",
      [receipt("item-letter")],
      { entityId: "ent-okafor", certainty: "sure" },
    ),
    memory(
      "mem-sam-saturday",
      "You want to ask Sam about Saturday.",
      "You",
      "wantsToAsk",
      "Sam about Saturday",
      [receipt("item-sam", { type: "time", startMs: 0, endMs: 6000 })],
      { entityId: "ent-sam" },
    ),
  ];

  const entity = (id: string, kind: EntityKind, name: string, role: string): EntityView => {
    // Counts are what the screens will find, so a person never sees a number that is not there.
    const mine = memories.filter((m) => m.entityId === id && m.status !== "letGo");
    const items = new Set(mine.flatMap((m) => m.receipts.map((r) => r.itemId)));
    return { id, kind, name, role, memoryCount: mine.length, itemCount: items.size };
  };

  const entities: EntityView[] = [
    entity("ent-leo", "person", "Leo", "Son"),
    entity("ent-ava", "person", "Ava", "Daughter"),
    entity("ent-gran", "person", "Gran (Margaret)", "Mother"),
    entity("ent-okafor", "person", "Mrs Okafor", "Leo’s teacher"),
    entity("ent-sam", "person", "Sam", "Partner"),
    entity("ent-chen", "person", "Dr Chen", "Dentist"),
    entity("ent-ridgeway", "place", "Ridgeway Science Centre", "Year 4 trip"),
    entity("ent-rowan", "place", "Rowan Court", "Where Gran lives"),
    entity("ent-dentist", "thing", "Dentist appointment", "Appointment"),
    entity("ent-lake", "thing", "Lake District cottage", "Half-term trip"),
    entity("ent-bin", "thing", "Bin day", "Household"),
  ];

  return { memories, entities };
}
